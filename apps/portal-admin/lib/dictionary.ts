/**
 * Looks up a key assembled at runtime (e.g. `"excluir" + "Titulo"`). Returns an
 * empty string for keys that do not resolve to copy, which is what the modal
 * wants for the types that supply their text some other way.
 */
export function dyn(L: Dic, key: string): string {
  const v = (L as unknown as Record<string, unknown>)[key];
  return typeof v === "string" ? v : "";
}
